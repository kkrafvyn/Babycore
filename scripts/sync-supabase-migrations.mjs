#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';
import { setTimeout as delay } from 'node:timers/promises';

const repoRoot = process.cwd();
const supabaseDir = path.join(repoRoot, 'supabase');
const migrationsDir = path.join(supabaseDir, 'migrations');
const manifestPath = path.join(supabaseDir, '.migration-sync-map.json');
const seedPath = path.join(supabaseDir, 'seed.sql');
const cliCommand = process.platform === 'win32' ? 'npx' : 'npx';

const hardResetFilename = '00-reset-public-schema.sql';
const sourceFiles = [
  path.join(repoRoot, 'DATABASE_SCHEMA.sql'),
  ...fs
    .readdirSync(path.join(repoRoot, 'database', 'sql'))
    .filter((filename) => filename.endsWith('.sql') && filename !== hardResetFilename)
    .sort((left, right) => left.localeCompare(right, undefined, { numeric: true }))
    .map((filename) => path.join(repoRoot, 'database', 'sql', filename)),
];

const ensureDirectory = (directoryPath) => {
  fs.mkdirSync(directoryPath, { recursive: true });
};

const loadJsonFile = (filename, fallback) => {
  if (!fs.existsSync(filename)) {
    return fallback;
  }

  try {
    return JSON.parse(fs.readFileSync(filename, 'utf8'));
  } catch {
    return fallback;
  }
};

const writeJsonFile = (filename, value) => {
  fs.writeFileSync(filename, `${JSON.stringify(value, null, 2)}\n`, 'utf8');
};

const toRelativePath = (absolutePath) =>
  path.relative(repoRoot, absolutePath).replace(/\\/g, '/');

const toMigrationName = (relativePath) =>
  relativePath
    .replace(/^database\/sql\//, '')
    .replace(/^DATABASE_SCHEMA\.sql$/, 'database_schema')
    .replace(/\.sql$/i, '')
    .replace(/[^a-zA-Z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '')
    .toLowerCase();

const createMigrationFile = (migrationName) => {
  const output = execSync(
    `${cliCommand} supabase migration new ${migrationName} --yes`,
    {
      cwd: repoRoot,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'pipe'],
    },
  );

  const match = output.match(/supabase[\\/]migrations[\\/](.+?\.sql)/i);
  if (!match?.[1]) {
    throw new Error(`Unable to determine migration filename from CLI output: ${output}`);
  }

  return match[1].replace(/\\/g, '/');
};

const existingManifest = loadJsonFile(manifestPath, {
  generatedAt: null,
  migrations: {},
});
let lastMigrationCreatedAt = 0;

ensureDirectory(migrationsDir);

if (!fs.existsSync(seedPath)) {
  fs.writeFileSync(
    seedPath,
    '-- Seed data is optional. Add deterministic local fixtures here when needed.\n',
    'utf8',
  );
}

const nextManifest = {
  generatedAt: new Date().toISOString(),
  migrations: {},
};

for (const sourceFile of sourceFiles) {
  const relativeSourcePath = toRelativePath(sourceFile);
  const sourceContents = fs.readFileSync(sourceFile, 'utf8').replace(/\r\n/g, '\n').trimEnd();
  const previousFilename = existingManifest.migrations?.[relativeSourcePath];
  const migrationFilename =
    previousFilename && fs.existsSync(path.join(migrationsDir, previousFilename))
      ? previousFilename
      : await (async () => {
          const elapsedMs = Date.now() - lastMigrationCreatedAt;
          if (lastMigrationCreatedAt !== 0 && elapsedMs < 1_100) {
            await delay(1_100 - elapsedMs);
          }

          const filename = createMigrationFile(toMigrationName(relativeSourcePath));
          lastMigrationCreatedAt = Date.now();
          return filename;
        })();

  const migrationPath = path.join(migrationsDir, migrationFilename);
  const renderedMigration = [
    `-- Source: ../${relativeSourcePath}`,
    '-- This file is generated by scripts/sync-supabase-migrations.mjs.',
    '-- Edit the source SQL file instead of this generated mirror.',
    '',
    sourceContents,
    '',
  ].join('\n');

  fs.writeFileSync(migrationPath, renderedMigration, 'utf8');
  nextManifest.migrations[relativeSourcePath] = migrationFilename;
}

for (const [relativeSourcePath, migrationFilename] of Object.entries(existingManifest.migrations || {})) {
  if (nextManifest.migrations[relativeSourcePath]) {
    continue;
  }

  const staleMigrationPath = path.join(migrationsDir, String(migrationFilename));
  if (fs.existsSync(staleMigrationPath)) {
    fs.rmSync(staleMigrationPath);
  }
}

writeJsonFile(manifestPath, nextManifest);

console.log(`Synced ${sourceFiles.length} SQL sources into supabase/migrations.`);
